#!/usr/bin/env python3
"""Generate 20_layout_spec.md (Class A) from the things the build actually uses: layout/book.css,
layout/tuning.json, work/palette.json, the icon tokens in the chapters, layout/hero_assets.json (when present)
and 21_asset_manifest.csv. Re-run after any change to those files so that the specification and the PDF agree."""
import collections, csv, glob, json, pathlib, re
ROOT = pathlib.Path(__file__).resolve().parent.parent
tun = json.loads((ROOT / 'layout/tuning.json').read_text(encoding='utf-8'))
pal = json.loads((ROOT / 'work/palette.json').read_text(encoding='utf-8'))
man = {r['Asset ID']: r for r in csv.DictReader(open(ROOT / '21_asset_manifest.csv', encoding='utf-8'))}
heroes = json.loads((ROOT / 'layout/hero_assets.json').read_text(encoding='utf-8')) if (ROOT / 'layout/hero_assets.json').exists() else {}

use = collections.Counter(); where = collections.defaultdict(set)
for f in sorted(glob.glob(str(ROOT / '10_manuscript_chapter_*.md'))):
    ch = re.search(r'chapter_(\d\d)_', f).group(1)
    for m in re.finditer(r'\{\{icon:([a-z0-9-]+)\}\}', pathlib.Path(f).read_text(encoding='utf-8')):
        use[m.group(1)] += 1; where[m.group(1)].add(ch)
all_icons = sorted(pathlib.Path(p).stem for p in glob.glob(str(ROOT / 'assets/icons/*.png')))

def aid(slug):
    return 'AST-' + slug.split('-')[1]

def desc(slug):
    r = man.get(aid(slug))
    return (r['Description'] if r else slug.split('-', 2)[2].replace('-', ' ')).split(' — ')[0][:70]

L = []
A = L.append
A('# 20 — Layout Specification (Class A)')
A('')
A('Generated by `tools/build_layout_spec.py` from `layout/book.css`, `layout/tuning.json`, `work/palette.json`, the icon tokens in the chapter files and `21_asset_manifest.csv`. The stylesheet is the executable form of this specification; where the two differ, regenerate this file. Asset IDs refer to `21_asset_manifest.csv` and `22_asset_extraction_log.md`.')
A('')
A('## 1. Format')
A('')
A('| Property | Screen edition | Print edition |')
A('|---|---|---|')
A('| Trim size | US Letter, 8.5 x 11 in (612 x 792 pt), portrait | the same |')
A('| Margins (top, outside, bottom, inside) | 52, 46, 50, 46 pt | the same |')
A('| Bleed | none (full-bleed cover drawn to the trim) | 0.125 in (9 pt) on the cover and on any full-bleed panel |')
A('| Safe area | text block 520 x 690 pt; no live text within 36 pt of the trim | the same |')
A('| Ground | parchment `#f4f2ea` (AST palette: parchment_page_2022) | white |')
A('| Colour | sRGB | sRGB master; convert to the printer\'s CMYK profile at export (palette CMYK values in §4) |')
A('| Image resolution | 150 ppi or more at placed size | 300 ppi or more at placed size; line art 600 ppi |')
A('| Metrics | identical in both editions: only colours differ, so both paginate alike | |')
A('')
A(f'Target extent: {tun.get("target_pages", "not set")} pages (QA tolerance 10%).')
A('')
A('## 2. Grid')
A('')
A('- Two columns of 252 pt with a 16 pt gutter; baseline (body leading) 12.2 pt. Measured line length: about 57 characters (target 50 to 70).')
A('- One continuous flow per chapter: text runs down the left column to the foot of the page and continues at the top of the right column. No element spans the columns inside a chapter; only the last page of a chapter has balanced columns.')
A('- Wider material is placed under the chapter banner (before the flow), at the end of the chapter (after the flow), or in a chapter set as one wide column (`ref_chapters` in the tuning file). The chapter intro (60 words or fewer) sits under the banner at a 400 pt measure.')
A('- Every chapter and appendix starts a new page. The Introduction is set in one column at a 392 pt measure.')
A('- Headings keep with the text that follows; a heading and a short block after it are bound together so that no heading is stranded at a column foot.')
A('')
A('## 3. Type scale')
A('')
A('| Role | Face | Size / leading | Notes |')
A('|---|---|---|---|')
for row in [
    ('Cover title', 'Cinzel Bold', '54 / 55 pt', 'letter-spacing 0.07 em; parchment on near-black'),
    ('Cover subtitle', 'Cinzel SemiBold', '20 pt and 12.5 pt', 'letter-spacing 0.32 to 0.36 em; gold rule between'),
    ('Chapter title (H1, in the banner)', 'Cinzel Bold', '19 / 21 pt', 'with number badge 25 pt and kicker 6.8 pt'),
    ('Section head (H2)', 'Cinzel SemiBold', '10.4 / 12.5 pt', 'section number in dark gold; hairline rule beneath'),
    ('Sub-section head (H3)', 'Cinzel SemiBold', '8.1 / 9.7 pt', 'capitals, letter-spacing 0.07 em'),
    ('Minor head (H4)', 'Libre Caslon Text Bold Italic', '8.9 / 11 pt', 'run-in labels are bold roman followed by a full sentence'),
    ('Body', 'Libre Caslon Text', '8.9 / 12.2 pt', 'justified, automatic hyphenation (en-GB), lining figures'),
    ('Chapter intro', 'Libre Caslon Text Italic', '10 / 13.8 pt', 'centred, 400 pt measure'),
    ('Example box', 'Libre Caslon Text', '8.5 / 11.6 pt', 'label in Cinzel SemiBold 6.9 pt capitals'),
    ('Table', 'Libre Caslon Text', '8.1 / 10.6 pt', 'header Cinzel SemiBold 6.5 pt capitals, reversed'),
    ('Caption', 'Libre Caslon Text Italic', '7.6 / 10 pt', 'bold roman lead-in; legend captions in two columns'),
    ('Glossary and F.A.Q.', 'Libre Caslon Text', '8.5 / 11.6 pt', 'bold headword or question'),
    ('Running head', 'Cinzel SemiBold', '6.6 pt', 'chapter left, section right; omitted on chapter openers'),
    ('Folio', 'Cinzel SemiBold', '8 pt', 'centred between two knot ornaments (AST-0075)'),
    ('Notes to tables', 'Libre Caslon Text', '8.9 pt', 'the book has no footnotes: a note is a sentence after its table'),
]:
    A('| ' + ' | '.join(row) + ' |')
A('')
A('Font substitutions (recorded in `22_asset_extraction_log.md`, Font Substitution): Cinzel for OptimusPrinceps (display), Libre Caslon Text for Adobe Caslon Pro (body). Both are licensed under the SIL Open Font License; the files and licences are in `assets/fonts/`. Static cuts are instantiated by `tools/make_fonts.py`, which also removes the discretionary st, ct and sp ligatures from the italic.')
A('')
A('## 4. Colour palette')
A('')
A('Sampled from the official PDFs during asset reconnaissance (`work/palette.json`).')
A('')
A('| Name | Hex | CMYK | Use |')
A('|---|---|---|---|')
for k, v in pal.items():
    A(f"| {k.replace('_', ' ')} | `{v['hex']}` | {v['cmyk']} | {v['use'].split(' (')[0][:80]} |")
A('')
A('Book-specific derivatives: gold accent `#c9ad6a` (badge, cover rule, kicker), dark gold `#7a622b` (section numbers, bullets, example labels), cross-reference ink `#5a4416`, example tint 11% node gold on parchment (7% in the print edition).')
A('')
A('## 5. Iconography')
A('')
A(f'The icon set is the 2022 symbol key extracted in Phase 0 ({len(all_icons)} icons, `assets/icons/`). Icons are set inline at 1.12 em high, aligned 0.22 em below the baseline, trimmed to their inked bounds (`tools/make_layout_assets.py`). All are placed on the parchment ground; no dark-ground variants are needed because banners carry text only. {len(use)} icons are used in the chapters; the others appear only on the icon reference page.')
A('')
A('| Asset ID | Icon | Meaning | Uses | Chapters |')
A('|---|---|---|---|---|')
for slug in all_icons:
    A(f"| {aid(slug)} | `{slug}` | {desc(slug)} | {use.get(slug, 0)} | {', '.join(sorted(where.get(slug, []))) or 'reference page only'} |")
A('')
A('## 6. Asset placement')
A('')
A('| Slot | Asset | Treatment |')
A('|---|---|---|')
A('| Cover | AST-0142 (lava-scale texture), logo-free crop | field of scales fading to near-black in the lower half; title set in the display face above it. The DARK SOULS wordmark is not placed (nominative use only, Gate 1 OQ-33) |')
A('| Chapter banner (hero slot) | per-chapter hero image where one is assigned (table below); otherwise AST-0142 crop | dark gradient under the whole title; number badge in gold |')
A('| Chapter end | AST-0082 (knot, rule, knot divider) | centred beneath the balanced columns; omitted when it would stand alone on a page |')
A('| Chapter-end gallery | product images from the chapter\'s pool (table below) | fills the empty foot of a chapter\'s last page |')
A('| Back cover | AST-0143 (dark stone ground with its light panel) | the opening and closing lines of the Introduction, centred in the panel |')
A('| Folio | AST-0075 (knot square) | one either side of the page number |')
A('| Front-matter rule | AST-0082 | under the Foreword and Contents titles |')
A('| Example box | tint and left rule in node gold | border and tint repeat on both parts when a box breaks |')
A('| Anatomy figures | see the figure table below | captions keyed to the numbered call-outs of each plate |')
A('| Icon reference page | every icon the rules use (see §5) | back matter, after the appendices; each entry links to the first section that uses the icon |')
A('')
A('Figures placed (from `layout/tuning.json`):')
A('')
A('| Asset | Position | Width | Caption |')
A('|---|---|---|---|')
for f in tun.get('figures', []):
    pos = f"top of chapter {f['chapter']}" if f['at'] == 'top' else (f"end of chapter {f['chapter']}" if f['at'] == 'end' else f"in {f['section'].replace('sec-', '§').replace('-', '.')}")
    A(f"| {f.get('asset', '')} | {pos} | {f.get('width', '')} | {re.sub(r'<[^>]+>', '', f.get('caption', ''))[:110]} |")
A('')
def _aid(path):
    m = re.search(r'ast-(\d{4})', path); return f'AST-{m.group(1)}' if m else ''
def _name(path):
    return re.sub(r'^ast-\d{4}-', '', pathlib.Path(path).stem)
if tun.get('heroes'):
    A('Chapter openers: every chapter and appendix has a designated hero image on its banner (from `layout/tuning.json`, key `heroes`). A render with a transparent ground stands on the foot of the banner and may rise above its head into the top margin; a wide image sits inside the banner. The banner reserves the hero\'s width so that the title never runs under it.')
    A('')
    A('| Opener | Hero asset | File | Height on the banner |')
    A('|---|---|---|---|')
    for ch, h in sorted(tun['heroes'].items()):
        bn = h.get('banner')
        if bn:
            label = f"Appendix {ch[4:].upper()}" if ch.startswith('app-') else f'Chapter {int(ch)}'
            A(f"| {label} | {_aid(bn['file'])} | `{_name(bn['file'])}` | {bn['h']} pt |")
    A('')
    A('Chapter-end galleries: where the last page of a chapter has 114 pt or more of empty text block under the closing ornament, the build fills it with product images from that chapter\'s pool, in one to three centred rows with captions in the display face. The build measures the room on a first pass and sizes the rows on a second; no image is set larger than 150 ppi allows; a gallery that would not fit is withdrawn. A gallery that nearly fills the room stands on the foot of the text block, and a smaller one is centred in the room.')
    A('')
    A('| Chapter | Gallery pool (in order; the build places as many as fit) |')
    A('|---|---|')
    for ch, h in sorted(tun['heroes'].items()):
        if h.get('end'):
            label = f"Appendix {ch[4:].upper()}" if ch.startswith('app-') else f'Chapter {int(ch)}'
            A(f"| {label} | {', '.join(f'{_aid(f)} `{_name(f)}`' for f in h['end'])} |")
    A('')
    masked = [f for f in tun.get('figures', []) if f.get('masks')]
    if masked:
        A('Withheld areas: ' + ', '.join(f.get('asset', '') for f in masked) + ' are placed with their painted illustrations blanked (`masks` in the tuning file; `withhold()` in `tools/make_layout_assets.py`), and call-out badges removed by the blanking are redrawn. The frames, icons, values, and call-outs are unchanged. The source plates in `assets/diagrams/` are untouched, so the blanking is removed by deleting the `masks` keys.')
        A('')
else:
    A('Chapter hero images: none assigned yet; every banner uses the AST-0142 crop.')
    A('')
A('## 7. Tables')
A('')
A('- Header row reversed (parchment on `#231f20`), Cinzel capitals; alternate rows banded with a 5% ink tint; hairline rule under every row.')
A('- Numeric cells centred; the first (label) column is never hyphenated.')
A('- Rows never split. A table of nine rows or fewer stays whole. A longer table may break between rows; its header row repeats, and no single row is left alone on either side of the break.')
A('- Tables sit inside a column. A table too wide for a column belongs to a chapter listed under `ref_chapters`, which is set as one wide column with running text capped at 430 pt.')
A('')
A('## 8. Examples, definitions, and call-outs')
A('')
A('- A worked example is a tinted box with a gold left rule and the label EXAMPLE in the display face; it follows the rule it illustrates and is kept whole when shorter than about 430 characters.')
A('- A definition is a paragraph with a bold run-in headword; the same form is used in the Glossary, where each entry is an anchor.')
A('- Optional rules open with the fixed three-sentence formula and carry no box.')
A('- Numbered procedures hang their numbers in the margin of the column; sub-steps are numbered 4.1, 4.2 and indented.')
A('')
A('## 9. Cross-references and notes')
A('')
A('- Every "(see §N.M)" is a link to its section; the section sign and number are set in cross-reference ink. A cited sub-section title links to the section that contains it.')
A('- Italic keywords link to their Glossary entries.')
A('- The book has no footnotes. A note to a table is a sentence set directly after the table.')
A('')
A('## 10. Front and back matter')
A('')
A('1. Cover (full bleed).')
A('2. Foreword, with the colophon at the foot of the page.')
A('3. Contents: three columns, chapter rows in the display face with hanging numbers, section rows beneath, page numbers on dotted leaders in a reserved right gutter.')
A('4. Chapters 1 to 20.')
A('5. Glossary (chapter 21) and F.A.Q. (chapter 22), in the two-column flow at 8.5 pt.')
A('6. Appendix A and Appendix B.')
A('7. Icon reference page.')
A('')
A('There is no separate index: the Glossary entries cite their owning sections, and every keyword in the text links to its entry.')
A('')
A('## 11. Cover design')
A('')
A('Ground `#0b0a09`. Title "DARK SOULS" in Cinzel Bold 54 pt and "THE BOARD GAME" in Cinzel SemiBold 20 pt, parchment, centred with the top of the title 1.55 in from the head; a 3.4 in gold rule; "SECOND EDITION RULEBOOK" in gold capitals. Below, from 4.4 in, the logo-free field of lava scales (AST-0142) under a radial fade to the ground colour. Foot line: "AN UNOFFICIAL, NON-COMMERCIAL FAN WORK". The official logo lock-ups (AST-0001 to AST-0005) and the cover paintings are not used.')
A('')
A('## 12. Outstanding asset requirements')
A('')
out = [r for r in man.values() if r['Status'].strip().upper().startswith(('BLOCKED', 'TO EXTRACT')) or 'PROVENANCE' in r['Licensing'].upper()]
A('| Asset ID | Description | Status | What is needed |')
A('|---|---|---|---|')
for r in out:
    need = 'ruling on FromSoftware / Bandai Namco key art (Gate 1 OQ-33)' if 'PROVENANCE' in r['Licensing'].upper() else ('extraction pending' if r['Status'].upper().startswith('TO EXTRACT') else next((s for s in re.split(r'(?<=[.;]) ', r['Notes']) if not s.startswith(('file', '(sub-entry'))), 'source or ruling needed')[:170])
    A(f"| {r['Asset ID']} | {r['Description'][:80]} | {r['Status']} | {need} |")
A('')
A('Painted key art is withheld until the rights question is answered, so chapter banners and chapter-end panels use product imagery and textures only. The rule booklets for nine bosses were not supplied (see `14_open_issues.md`).')
A('')
A('### Substitutions')
A('')
A('| Original | Substitute | Where recorded |')
A('|---|---|---|')
A('| OptimusPrinceps (display face of the source books) | Cinzel, SIL OFL | manifest FONT-01 |')
A('| Adobe Caslon Pro (body face) | Libre Caslon Text, SIL OFL | manifest FONT-02 |')
A('| Helvetica (small print) | none: small print is set in the body face | manifest FONT-03 |')
A('| DARK SOULS logo lock-up on the cover (AST-0001 to AST-0006) | the title set in Cinzel; nominative use only | Gate 1 OQ-33; manifest placement column |')
A('| Painted cover and chapter art (held under Provenance Review) | cover: logo-free crop of the lava-scale texture AST-0142; openers and chapter ends: miniature, tile, board, dice, and token renders | `22_asset_extraction_log.md`, Provenance Review |')
A('| Painted illustrations inside the placed anatomy plates | blanked areas (see Withheld areas, §6) | `layout/tuning.json` |')
A('| Card-style example boxes and framed tables (AST-0083 to AST-0088) | boxes and tables drawn in CSS | manifest placement column |')
A('| Source diagrams that carry source text or show unused components | not placed; the seven plates listed in §6 are placed | manifest placement column |')
A('')
A('## 13. Build')
A('')
A('```')
A('python3 tools/make_fonts.py            # static font cuts')
A('python3 tools/build_pdf.py             # build/book_screen.pdf (add --edition print for the print edition)')
A('python3 tools/qa_pdf.py                # automated QA; exits 1 on any failure')
A('python3 tools/build_layout_spec.py     # regenerate this file')
A('```')
A('')
A('Decisions made by eye (figure positions, crops, single-column chapters, hero images, target extent) live in `layout/tuning.json` so that every build repeats them.')
(ROOT / '20_layout_spec.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('20_layout_spec.md written:', len(L), 'lines;', len(use), 'icons used;', len(out), 'outstanding assets')
